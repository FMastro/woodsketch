#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.md: every package WoodSketch is built with and its license.

    python -I scripts/make-notices.py            # write the file
    python -I scripts/make-notices.py --check    # fail if the file isn't what this would write

CI runs `--check` (the `notices` job), so the file can't drift away from the dependencies: a
`cargo add`, a version bump or a `cargo update` that changes what ships fails until the notices
are written again. That is the whole reason this exists -- the file was kept by hand before and
went stale, and a stale notices file is a licensing problem rather than an untidy one.

What goes in:

- Every package in the dependency graph except WoodSketch's own crates and anything reached only
  as a dev-dependency. Dev-dependencies are the test harness; they are not in the app. Build
  dependencies are kept, since they are part of producing it.
- No platform filtering, on purpose. The same file ships beside the Windows, macOS and Linux
  builds, so it has to name the packages all three use; filtering to the machine that ran this
  is how the macOS notices came to be missing every `objc2` package.
- The fonts in `assets/fonts`, which `cargo metadata` cannot see: they are `include_bytes!`d
  into the executable rather than reached through a package, so nothing else here would ever
  mention them. The SIL Open Font License asks to travel with the font it covers, and that font
  travels inside the program -- which makes this file the only place it can travel. A font put
  there without its license beside it stops this script, and so fails the `notices` job.

Licenses with the same text are listed once, under every package that carries it, with all of
their copyright lines together -- a hundred copies of the MIT license differing only in the
holder's name is no use to a reader. Where a package offers a choice, the permissive option is
taken (for `self_cell`, Apache-2.0, not GPL-2.0), so the copyleft text is left out: it is not
the license WoodSketch is used under.

License texts are written exactly as the package ships them. The generator this replaces pulled
every line containing the word "copyright" out of the text it quoted, which left holes in the
middle of the licenses themselves.
"""

import argparse
import difflib
import json
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NOTICES = ROOT / "THIRD-PARTY-NOTICES.md"
# Fonts built into the app, and the licenses that came with them, side by side in one folder.
FONTS = ROOT / "assets/fonts"
FONT_FILE = re.compile(r"\.(ttf|otf|ttc)$", re.IGNORECASE)

# What a license file is called, in the order to read them.
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE)", re.IGNORECASE)
# A copyright line, which is listed per group rather than repeated in every text.
COPYRIGHT = re.compile(r"^\s*(copyright\b|\(c\)\s|©)", re.IGNORECASE)
# A license we don't take when the package offers something else.
COPYLEFT = re.compile(r"GENERAL PUBLIC LICENSE", re.IGNORECASE)

PREAMBLE = """# Third-party notices

WoodSketch is built with the open-source packages listed here, each used under its own license.
Where a package offers a choice, the permissive one is taken (for `self_cell`, Apache-2.0, not
GPL-2.0).

Licenses with the same text are listed once, naming every package that carries it and every
copyright notice that came with them. Packages reached only as dev-dependencies are left out:
they are the test harness and are not in the app.

Generated by `scripts/make-notices.py` from `cargo metadata` and the license files the packages
ship. Don't edit it by hand -- run the script, which CI checks.
"""


def metadata():
    """`cargo metadata` for the whole graph, every feature, no platform filtering."""
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--all-features", "--locked"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if out.returncode != 0:
        sys.exit(f"cargo metadata failed:\n{out.stderr}")
    return json.loads(out.stdout)


def shipped(meta):
    """The packages that reach the app, by id: everything but WoodSketch's own crates and the
    dev-dependencies, walked from the workspace outwards so a dev-only package's own
    dependencies drop out with it."""
    deps = {node["id"]: node for node in meta["resolve"]["nodes"]}
    ours = set(meta["workspace_members"])
    seen, edge = set(), list(ours)
    while edge:
        at = edge.pop()
        for dep in deps[at]["deps"]:
            # A package wanted as a dev-dependency *and* as a real one stays.
            if all(kind.get("kind") == "dev" for kind in dep["dep_kinds"]):
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                edge.append(dep["pkg"])
    return seen - ours


def licenses_of(package):
    """The license files a package ships, as (filename, text), the ones it doesn't grant under
    left out. Its source has to be unpacked, which `cargo fetch` does."""
    where = pathlib.Path(package["manifest_path"]).parent
    if not where.is_dir():
        sys.exit(f"{package['name']} {package['version']} isn't unpacked: run `cargo fetch`")
    choice = " OR " in (package["license"] or "").upper() or "/" in (package["license"] or "")
    files = []
    for path in sorted(p for p in where.iterdir() if p.is_file() and LICENSE_FILE.match(p.name)):
        text = path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
        if not text:
            continue
        if choice and COPYLEFT.search(text):
            continue
        files.append((path.name, text))
    return files


def same_license(text):
    """What makes two license texts the same one: the words, with the copyright holders and the
    wrapping taken out. Used to group them, never to change what is written out."""
    kept = [line for line in text.splitlines() if not COPYRIGHT.match(line)]
    return re.sub(r"\s+", " ", " ".join(kept)).strip().lower()


def copyrights(text):
    """The copyright lines of one license file, as written."""
    return [line.strip() for line in text.splitlines() if COPYRIGHT.match(line)]


def fonts():
    """The fonts inside the executable, and the license texts beside them.

    Paired by folder rather than by name: a license file is named after the license
    (`OFL-1.1-...`) and not after the font, while everything in there covers something in there.
    What has to hold is that no font ships without one, which is what the exit below is for.
    """
    if not FONTS.is_dir():
        return [], []
    beside = sorted(p for p in FONTS.iterdir() if p.is_file())
    files = [p for p in beside if FONT_FILE.search(p.name)]
    texts = [p for p in beside if not FONT_FILE.search(p.name)]
    if files and not texts:
        sys.exit(f"{FONTS.relative_to(ROOT)} has fonts and no license beside them. A font built into the app ships with the app, and so must its license.")
    return files, texts


def notices(meta):
    """The whole file."""
    wanted = shipped(meta)
    packages = sorted(
        (p for p in meta["packages"] if p["id"] in wanted),
        key=lambda p: (p["name"].lower(), p["version"]),
    )

    out = [PREAMBLE, "## Packages\n", "| Package | Version | License |", "|---|---|---|"]
    for p in packages:
        out.append(f"| {p['name']} | {p['version']} | {p['license'] or 'see the package'} |")

    # Group by license text. `held` keeps each group's packages, copyright lines and one text.
    held = {}
    silent = []
    for p in packages:
        named = f"{p['name']} {p['version']}"
        files = licenses_of(p)
        if not files:
            silent.append((named, p["license"] or "not stated"))
            continue
        for _, text in files:
            group = held.setdefault(same_license(text), {"packages": [], "notices": set(), "text": text})
            if named not in group["packages"]:
                group["packages"].append(named)
            group["notices"].update(copyrights(text))

    # The fonts are listed where a reader looks for what is in the program, and their licenses
    # go through the same grouping as the packages' below, so one OFL is written out once
    # however many fonts carry it.
    font_files, font_texts = fonts()
    if font_files:
        out.append("\n## Fonts built into the app\n")
        out.append(
            "Built into the executable rather than reached as packages, so `cargo metadata`"
            " doesn't see them. Their licenses are below, with everything else's.\n"
        )
        out.append("| Font | Where |")
        out.append("|---|---|")
        for font in font_files:
            out.append(f"| {font.name} | `{font.relative_to(ROOT).as_posix()}` |")
    for text_file in font_texts:
        text = text_file.read_text(encoding="utf-8", errors="replace").strip()
        carried = ", ".join(f.name for f in font_files)
        group = held.setdefault(same_license(text), {"packages": [], "notices": set(), "text": text})
        if carried not in group["packages"]:
            group["packages"].append(carried)
        group["notices"].update(copyrights(text))

    out.append("\n## Licenses\n")
    # Widest first, then by name, so the file is stable and the licenses that matter most are up
    # front rather than buried among the one-package ones.
    for group in sorted(held.values(), key=lambda g: (-len(g["packages"]), g["packages"][0])):
        out.append(f"### Used by {len(group['packages'])} package(s): {', '.join(group['packages'])}\n")
        if group["notices"]:
            out.append("Copyright notices:\n")
            out.extend(f"- {line}" for line in sorted(group["notices"]))
            out.append("")
        out.append("```")
        out.append(group["text"])
        out.append("```\n")

    if silent:
        out.append("## Packages that ship no license file\n")
        out.append(
            "These name their license in their own metadata without including its text. Every"
            " license named here is written out above, under the packages that do ship it.\n"
        )
        out.append("| Package | Version | License |")
        out.append("|---|---|---|")
        for named, license_name in silent:
            name, version = named.rsplit(" ", 1)
            out.append(f"| {name} | {version} | {license_name} |")
        out.append("")

    return "\n".join(out).rstrip() + "\n"


def main():
    parsed = argparse.ArgumentParser(description="Write or check THIRD-PARTY-NOTICES.md.")
    parsed.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parsed.parse_args()

    written = notices(metadata())
    if not args.check:
        NOTICES.write_text(written, encoding="utf-8", newline="\n")
        print(f"wrote {NOTICES.relative_to(ROOT)}")
        return 0

    # Line endings are git's business, not this check's.
    on_disk = NOTICES.read_text(encoding="utf-8").replace("\r\n", "\n")
    if on_disk == written:
        print("THIRD-PARTY-NOTICES.md is up to date")
        return 0
    diff = difflib.unified_diff(
        on_disk.splitlines(), written.splitlines(), "THIRD-PARTY-NOTICES.md", "what the dependencies say", lineterm="", n=1
    )
    print("\n".join(list(diff)[:80]))
    print(
        "\nTHIRD-PARTY-NOTICES.md doesn't match the dependencies."
        "\nRun `python -I scripts/make-notices.py` and commit the result."
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
